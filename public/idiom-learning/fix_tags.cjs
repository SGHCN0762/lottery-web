const getTags = (word) => {
  const tags = [];
  
  if (primarySchoolIdioms.has(word)) tags.push('primary');
  if (middleSchoolIdioms.has(word)) tags.push('middle');
  if (highSchoolIdioms.has(word)) tags.push('high');
  if (civilServiceIdioms.has(word)) tags.push('civil');
  
  return tags;
};

const indexData = JSON.parse(fs.readFileSync(path.join(__dirname, 'idioms_index.json'), 'utf8'));
const numFiles = indexData.meta?.num_files || 10;

let totalIdioms = 0;
let totalTags = 0;

for (let i = 1; i <= numFiles; i++) {
  const fileName = `idioms_${String(i).padStart(2, '0')}.json`;
  const filePath = path.join(__dirname, fileName);
  const data = fs.readFileSync(filePath, 'utf8');
  const parsed = JSON.parse(data);
  const idioms = parsed.idioms || [];
  
  let tagCount = 0;
  idioms.forEach(idiom => {
    const tags = getTags(idiom.word);
    idiom.tags = tags;
    tagCount += tags.length;
  });
  
  parsed.meta.tags_added = true;
  parsed.meta.updated_at = new Date().toISOString();
  
  fs.writeFileSync(filePath, JSON.stringify(parsed, null, 2), 'utf8');
  
  totalIdioms += idioms.length;
  totalTags += tagCount;
  console.log(`${fileName}: ${idioms.length} idioms, ${Math.round(tagCount / idioms.length * 100) / 10} tags/idiom`);
}

